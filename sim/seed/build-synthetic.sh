#!/usr/bin/env bash
# Rebuild sim/seed/synthetic.sql: the synthetic fixture `simctl load synthetic` restores.
#
#   synthetic-base.sql                 the tables the QT migrations build on, and auth.users
#   trade-ngin migrations              014, 017 and 021-029, read from the engine image
#                                      (ENGINE_IMAGE), so they match the engine under test
#   algolens-api/migrations/003        screen access (auth.user_screen_access, investor)
#   synthetic-day.sql                  one QT day
#
# trade-ngin's other migrations need tables the fixture does not have (backtest.*, signals).
#
#   bash sim/seed/build-synthetic.sh
set -euo pipefail
export MSYS_NO_PATHCONV=1

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
image="${ENGINE_IMAGE:-trade-ngin:rpc-0b9dbf6e}"
migrations=(014_contract_metadata_fee_per_contract 017_live_results_roll_costs 021_qt_books
            022_strategy_config 023_qt_command_log 024_drop_retired_qt_tables
            025_qt_command_log_hardening 027_qt_daily_cutoff 028_ops_data_ready 029_qt_rescind)

out="$here/synthetic.sql"
{
    echo "-- GENERATED by sim/seed/build-synthetic.sh from $image; do not edit."
    echo "-- Restored into an empty new_algo_data by \`simctl load synthetic\`."
    echo "\\set ON_ERROR_STOP on"
    echo
    cat "$here/synthetic-base.sql"
    for m in "${migrations[@]}"; do
        echo
        echo "-- ===== trade-ngin migrations/$m.sql ($image)"
        docker run --rm --entrypoint cat "$image" "/app/migrations/$m.sql"
    done
    echo
    echo "-- ===== algolens-api/migrations/003_screen_access.sql"
    cat "$repo/algolens-api/migrations/003_screen_access.sql"
    echo
    echo "-- ===== sim/seed/synthetic-day.sql"
    cat "$here/synthetic-day.sql"
} | sed 's/\r$//' > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
